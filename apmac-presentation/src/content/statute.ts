export function article(n: number): Article {
  const a = ARTICLES.find((x) => x.n === n);
  if (!a) throw new Error(`Unknown article ${n}`);
  return a;
}

export function chapter(n: number): Chapter {
  const c = CHAPTERS.find((x) => x.n === n);
  if (!c) throw new Error(`Unknown chapter ${n}`);
  return c;
}

export function block<K extends Block["kind"]>(n: number, id: string, kind: K): Extract<Block, { kind: K }> {
  const b = article(n).blocks.find((x) => x.id === id);
  if (!b || b.kind !== kind) throw new Error(`Article ${n}: block "${id}" (${kind}) not found`);
  return b as Extract<Block, { kind: K }>;
}
